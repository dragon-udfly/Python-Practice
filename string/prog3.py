# string slicing 
text = "this is a text"
substring_one = text[:5] # from begining to fifth
substring_two = text[2:9] # from third character to nineth
substring_three = text[5:] # from 6 th character to end

print(f"Substring: {substring_one}")
print(f"Substring: {substring_two}")
print(f"Substring: {substring_three}")